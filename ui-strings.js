export const UI_KEYS = Object.keys(UI_STRINGS.english);

// Look up a UI string, falling back to English when a language or key is
// missing (never a blank label). {vars} are substituted into the string.
export function uiText(language, key, vars = {}) {
  const table = UI_STRINGS[language] || UI_STRINGS.english;
  let s = table[key] ?? UI_STRINGS.english[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

